"""A check of everything that a seat sees, for the features: plays games of every kind, with every species discovered, and lists each piece of information
in the projected view (its path, a few values), the features that carry it, and what is left out. Writes docs/ai-visible-info.md.

    .venv/Scripts/python.exe -m seti_ai.visible_info [--out ../../docs/ai-visible-info.md]

A path that holds only the placeholder "?" is a hidden thing of which only the count is seen. The check also prints the paths that no feature carries
(there should be none but the excluded ones) and the paths where the opponent's information could leak (a value that differs between two states that
differ only in what the seat cannot see: tests/test_features.py).
"""

from __future__ import annotations

import argparse
import random
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

from seti_engine import engine
from seti_engine.models import GameState, Options
from seti_engine.projection import project, to_act

from . import features

sys.path.insert(0, str(Path(__file__).parents[3] / "engine" / "tests"))


def leaves(path: str, x: Any, out: dict[str, set[str]]) -> None:
    if isinstance(x, dict):
        for k, v in x.items():
            leaves(f"{path}.{k}", v, out)
    elif isinstance(x, (list, tuple)):
        out[f"{path}.len"].add(str(len(x)))
        for i, v in enumerate(x[:40]):
            leaves(f"{path}[{i}]", v, out)
    else:
        out[path].add(repr(x)[:30])


def species_states() -> list[GameState]:
    """Games with each species discovered (the helpers of the engine tests make the discovery)."""
    from test_species import discover, game

    states: list[GameState] = []
    for first, second in (("anomalies", "centaurians"), ("exertians", "mascamites"), ("oumuamua", "anomalies")):
        states.append(discover(game(first, second), 0).state)
    return states


def play(options: Options, steps: int, seed: int) -> list[GameState]:
    rnd = random.Random(seed)
    r = engine.start(options)
    out = []
    for n in range(steps):
        if not r.legal:
            break
        r = engine.apply(r.state, rnd.choice(r.legal))
        if n % 25 == 0:
            out.append(r.state)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="../../docs/ai-visible-info.md")
    a = ap.parse_args()
    seen: dict[str, set[str]] = defaultdict(set)
    states: list[GameState] = []
    for seed in range(3):
        states += play(Options(players=2, seed=seed), 400, seed)
        states += play(Options(players=1, seed=seed), 300, seed)
        states += play(Options(players=2, seed=seed, expansion=True, organizations=True), 300, seed)
    states += species_states()
    for s in states:
        seat = to_act(s)
        if seat is None:
            continue
        view = project(s, seat, previews=False)
        data = features.relative_view(view)
        for top, sub in data.items():
            leaves(top, sub, seen)
    norm: dict[str, set[str]] = defaultdict(set)
    for p, vals in seen.items():
        norm[re.sub(r"\[\d+\]", "[]", p)] |= vals
    lines = [
        "# What a seat sees, and the features (generated by `seti_ai.visible_info`)",
        "",
        f"{len(norm)} kinds of information in the projected view over {len(states)} positions of base, solo, expansion and species games.",
        "Every one of them is a feature of the agent (`features.py` walks the whole view), except what is listed as excluded. A value `'?'` is a hidden thing",
        "of which only the number is seen (the deck, the other hands, the face-down tiles, an undiscovered species).",
        "",
        "## Excluded from the features",
        "",
    ]
    lines += [f"- `{k}`: {v}" for k, v in features.EXCLUDED.items()]
    lines += ["", "## Everything else, by part of the game", ""]
    groups: dict[str, list[str]] = defaultdict(list)
    for p in sorted(norm):
        head = ".".join(p.split(".")[:2]) if p.startswith("state.") else p.split(".")[0]
        groups[head].append(p)
    for head, paths in groups.items():
        lines += [f"### {head}", ""]
        for p in paths:
            shown = sorted(norm[p])
            hidden = " (hidden: only the count)" if shown == ["'?'"] else ""
            lines.append(f"- `{p}`: {', '.join(shown[:6])}{'...' if len(shown) > 6 else ''}{hidden}")
        lines.append("")
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(norm)} paths from {len(states)} positions written to {a.out}")


if __name__ == "__main__":
    main()
