"""Generate the protocol JSON Schema from the pydantic models (decision D11): packages/protocol/schema/protocol.schema.json.

Run from the repo root: python tools/engine/gen_protocol.py   (uses the engine's virtualenv: cd services/engine && python -m uv run python ../../tools/engine/gen_protocol.py)
The TypeScript types are generated from this file by `pnpm --filter @seti/protocol generate`. Neither file is edited by hand.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "services" / "engine" / "src"))

from seti_engine.protocol import INPUT_MODELS, MODELS, PROTOCOL_VERSION, build_schemas  # noqa: E402


def tuples(node: object) -> None:
    """json-schema-to-typescript reads tuples as `items: [...]` (draft 7), not as `prefixItems`."""
    if isinstance(node, dict):
        if "prefixItems" in node:
            node["items"] = node.pop("prefixItems")
            node["additionalItems"] = False
        for value in node.values():
            tuples(value)
    elif isinstance(node, list):
        for value in node:
            tuples(value)


def merged() -> dict:
    """One schema document: every model and every nested definition under $defs, and a root object that refers to all of them."""
    defs: dict = {}
    for name, schema in build_schemas().items():
        schema = dict(schema)
        for key, sub in schema.pop("$defs", {}).items():
            defs[key] = sub
        schema.pop("title", None)
        schema["title"] = name
        defs[name] = schema
    out = {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "title": "SetiProtocol",
        "description": f"Protocol version {PROTOCOL_VERSION}. Generated by tools/engine/gen_protocol.py; do not edit.",
        "type": "object",
        "properties": {name: {"$ref": f"#/$defs/{name}"} for name in MODELS},
        "additionalProperties": False,
        "$defs": dict(sorted(defs.items())),
    }
    for name, schema in defs.items():  # what the service sends always has every field; only the inputs have optional ones
        if name not in INPUT_MODELS and "properties" in schema:
            schema["required"] = sorted(schema["properties"])
    tuples(out)
    return out


def render() -> str:
    return json.dumps(merged(), indent=2, sort_keys=True) + "\n"


if __name__ == "__main__":
    out = ROOT / "packages" / "protocol" / "schema" / "protocol.schema.json"
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out} (protocol {PROTOCOL_VERSION})")
