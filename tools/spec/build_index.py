"""Build docs/spec/rules-index.md and check the spec for broken references.

Usage: python tools/spec/build_index.py        (from the repo root)

A rule is DEFINED by a line starting with "- **ID**" or a heading or bold title ending in "(ID)".
A rule is REFERENCED anywhere else in the spec. The check fails if an ID is defined twice, referenced
but not defined, or if an ambiguity A-NNN is referenced but missing from ambiguities.md.
"""
import glob
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
SPEC = os.path.join(ROOT, 'docs', 'spec')
ID = r'[A-Z]+(?:-[A-Z0-9]+)*-\d+'
files = sorted(f for f in glob.glob(os.path.join(SPEC, '*.md'))
               if os.path.basename(f) not in ('rules-index.md', 'README.md', 'ambiguities.md', 'card-verification-summary.md', 'owner-confirmations.md'))

defs, refs, where = {}, {}, {}
for f in files:
    name = os.path.basename(f)
    for n, line in enumerate(open(f, encoding='utf-8'), 1):
        m = re.match(r'\s*-\s+\*\*(' + ID + r')\*\*\s*(.*)', line)
        if m:
            rid = m.group(1)
            defs.setdefault(rid, []).append((name, n, m.group(2)[:110]))
            line = line[m.end(1):]
        else:
            for t in re.finditer(r'^(?:#{2,4}\s.*|\*\*[^*]*)\((' + ID + r')\)', line):
                defs.setdefault(t.group(1), []).append((name, n, line.strip('#* \n')[:110]))
        for r in re.finditer(r'\b(' + ID + r')\b', line):
            refs.setdefault(r.group(1), set()).add(name)

problems = []
for rid, d in defs.items():
    if len(d) > 1:
        problems.append('defined more than once: %s in %s' % (rid, ', '.join('%s:%d' % (a, b) for a, b, _ in d)))
for rid in sorted(refs):
    if rid not in defs and not re.match(r'^A-\d+$', rid):
        problems.append('referenced but not defined: %s (in %s)' % (rid, ', '.join(sorted(refs[rid]))))
amb = open(os.path.join(SPEC, 'ambiguities.md'), encoding='utf-8').read()
amb_ids = set(re.findall(r'^## (A-\d+)', amb, re.M))
for f in files:
    for a in re.findall(r'\b(A-\d+)\b', open(f, encoding='utf-8').read()):
        if a not in amb_ids:
            problems.append('ambiguity %s referenced in %s but not in ambiguities.md' % (a, os.path.basename(f)))

order = {}
for rid, d in defs.items():
    order.setdefault(d[0][0], []).append((d[0][1], rid, d[0][2]))
out = ['# Rules index\n', 'Generated by `tools/spec/build_index.py`. Do not edit by hand. %d rules defined in %d files.\n' % (len(defs), len(order))]
for name in sorted(order):
    out.append('\n## %s\n' % name)
    out.append('| Rule | Summary |\n|---|---|')
    for n, rid, text in sorted(order[name]):
        out.append('| %s | %s |' % (rid, text.replace('|', '/')))
open(os.path.join(SPEC, 'rules-index.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(defs), 'rules defined,', len(refs), 'ids referenced,', len(amb_ids), 'ambiguities')
for p in sorted(set(problems)):
    print('PROBLEM:', p)
sys.exit(1 if problems else 0)
